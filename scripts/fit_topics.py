"""Fit BERTopic ONCE on the historical negative-review population. Never
refit automatically - every daily run of pipeline/topics.py only calls
.transform() against whatever this script saves. See docs/decisions.md for
what breaks if this were refit daily instead (topic ids have no persistent
meaning across separate fits).

Trains on rows strictly before the ingest window (timestamp < window_start),
the same temporal-split discipline as scripts/train_baseline.py, over the
real star-rating-defined negative population (rating <= 2 - see
pipeline/embed.filter_negative). NOT a 20-30k sample: this category only has
~9,300 negative reviews total, well under that, so the full population is
used instead of subsampling. See docs/decisions.md.

Not wired into a Makefile target - a deliberate one-off step, like
scripts/train_baseline.py and scripts/download_model.py.
"""

import argparse
import hashlib
import json
import pickle
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
import yaml
from bertopic import BERTopic
from hdbscan import HDBSCAN
from umap import UMAP

from pipeline.embed import build_embedding_model, filter_negative
from pipeline.features import build_text_column
from pipeline.ingest import load_config, load_raw_reviews, resolve_window


def select_training_rows(df: pd.DataFrame, window_start: pd.Timestamp) -> pd.DataFrame:
    train_df = df.loc[df["timestamp"] < window_start]
    return filter_negative(train_df)


def build_topic_model(topics_config: dict) -> BERTopic:
    umap_model = UMAP(**topics_config["umap"])
    hdbscan_model = HDBSCAN(
        **topics_config["hdbscan"],
        metric="euclidean",
        cluster_selection_method="eom",
        prediction_data=True,  # required for approximate_predict in .transform() later
    )
    return BERTopic(umap_model=umap_model, hdbscan_model=hdbscan_model, calculate_probabilities=False)


def serialize_and_hash(fitted_model: BERTopic) -> tuple[bytes, str]:
    # pickle, not safetensors: safetensors drops the fitted UMAP/HDBSCAN
    # state, and BERTopic's own docs note its .transform() then falls back
    # to a different (cosine-similarity) assignment method that "can yield
    # different results" - directly at odds with this stage's stability
    # requirement. This is a locally-produced artifact, not untrusted
    # third-party data, so pickle's usual security caveat doesn't apply here.
    artifact_bytes = pickle.dumps(fitted_model)
    sha256 = hashlib.sha256(artifact_bytes).hexdigest()
    return artifact_bytes, sha256


def append_registry_entry(registry_path: Path, entry: dict) -> None:
    registry_path.parent.mkdir(parents=True, exist_ok=True)
    registry = json.loads(registry_path.read_text()) if registry_path.exists() else []
    registry.append(entry)
    registry_path.write_text(json.dumps(registry, indent=2))


def write_topic_names_template(topic_model: BERTopic, path: Path) -> None:
    """Auto-generates a starting point keyed by topic id -> BERTopic's own
    keyword-based label. Meant to be hand-edited into readable business
    language afterward - see the header this writes into the file."""
    info = topic_model.get_topic_info()
    labels = {int(row.Topic): row.Name for row in info.itertuples()}
    header = (
        "# Auto-generated by scripts/fit_topics.py - hand-edit these labels into\n"
        "# readable business language, then commit.\n"
        "# Topic -1 is BERTopic's outlier bucket (documents that didn't fit any\n"
        "# cluster confidently), not a real theme.\n"
        "# Re-run fit_topics.py only deliberately: a refit changes what these\n"
        "# topic ids mean, so this file needs re-editing after every refit.\n"
    )
    path.write_text(header + yaml.safe_dump(labels, sort_keys=True, allow_unicode=True))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="config/pipeline.yaml")
    args = parser.parse_args()
    config = load_config(args.config)

    raw_path = Path(config["paths"]["raw_local"]) / Path(config["dataset"]["hf_path"]).name
    reference_date = pd.Timestamp(config["window"]["reference_date"])
    window_start, _ = resolve_window(reference_date, config["window"]["lookback_days"])

    df = load_raw_reviews(raw_path)
    train_df = select_training_rows(df, window_start)

    texts = build_text_column(train_df).tolist()
    embedding_model = build_embedding_model(config)
    embeddings = embedding_model.encode(texts, show_progress_bar=True)

    topic_model = build_topic_model(config["topics"])
    topics, _ = topic_model.fit_transform(texts, embeddings=embeddings)

    artifact_bytes, sha256 = serialize_and_hash(topic_model)
    model_path = Path("models") / f"bertopic-{sha256[:12]}.pkl"
    model_path.parent.mkdir(parents=True, exist_ok=True)
    model_path.write_bytes(artifact_bytes)

    info = topic_model.get_topic_info()
    n_topics = int((info["Topic"] != -1).sum())
    n_outliers = int((pd.Series(topics) == -1).sum())

    entry = {
        "sha256": sha256,
        "artifact_path": str(model_path),
        "trained_at": datetime.now(timezone.utc).isoformat(),
        "training_rows": int(len(train_df)),
        "n_topics": n_topics,
        "n_outliers": n_outliers,
        "umap_config": config["topics"]["umap"],
        "hdbscan_config": config["topics"]["hdbscan"],
        "embedding_model": config["model"]["embedding"]["name"],
        "embedding_model_revision": config["model"]["embedding"]["revision"],
    }
    append_registry_entry(Path(config["topics"]["registry_path"]), entry)

    topic_names_path = Path("config/topic_names.yaml")
    write_topic_names_template(topic_model, topic_names_path)

    print(f"trained on {len(train_df)} negative reviews")
    print(f"topics found: {n_topics} (+ {n_outliers} outliers)")
    print(f"sha256: {sha256}")
    print(f"artifact: {model_path}")
    print(f"wrote starting labels to {topic_names_path} - hand-edit these")
    print("to use this model, set topics.active_model_sha in config/pipeline.yaml")


if __name__ == "__main__":
    main()
